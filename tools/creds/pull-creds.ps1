# Pulls team credentials from the event credential vault into a gitignored .env file,
# so every project and agent loads keys from one place instead of copy-pasting them.
#
# Token lookup (first found wins):
#   1. $env:HACKATHON_TEAM_TOKEN
#   2. The key saved in the API console (tools/api-console/src/secrets.json, DPAPI-encrypted)
#
# Usage:
#   .\pull-creds.ps1                         # reveal all credentials -> <repo>\.env
#   .\pull-creds.ps1 -List                   # metadata only, reveals nothing
#   .\pull-creds.ps1 -Name 'AWS Sandbox Key' # reveal only the named credential(s)
#   .\pull-creds.ps1 -OutFile ..\..\challenges\x\y\.env
#
# Every reveal is audit-logged by the event, so only pull what you need.

param(
    [switch]$List,
    [string[]]$Name,
    [string]$OutFile
)

$ErrorActionPreference = 'Stop'
$ApiBase  = 'https://cdao.hackathon.maximus.com'
$TeamUuid = '7e3a3e89-0e20-42b5-b646-8a857cd51012'
$RepoRoot = Split-Path (Split-Path $PSScriptRoot -Parent) -Parent
if (-not $OutFile) { $OutFile = Join-Path $RepoRoot '.env' }

# --- Token ---
$Token = $env:HACKATHON_TEAM_TOKEN
if (-not $Token) {
    $ConsoleSrc  = Join-Path $RepoRoot 'tools\api-console\src'
    $SecretsPath = Join-Path $ConsoleSrc 'secrets.json'
    if (Test-Path $SecretsPath) {
        . (Join-Path $ConsoleSrc 'secrets.ps1')
        $saved = Get-Content $SecretsPath -Raw | ConvertFrom-Json
        if ($saved.apiKeyProtected) { $Token = Unprotect-Secret $saved.apiKeyProtected }
    }
}
if (-not $Token) {
    throw 'No team token. Save it in the API console, or set $env:HACKATHON_TEAM_TOKEN.'
}

$Headers = @{ Authorization = "Bearer $Token" }
$Base    = "$ApiBase/api/teams/$TeamUuid/credentials"

# --- List ---
$creds = (Invoke-RestMethod -Uri "$Base/" -Headers $Headers).credentials
if ($List) {
    $creds | Select-Object name, credential_key, source, expires_at, access_count, uuid | Format-Table -AutoSize
    return
}
if ($Name) {
    $creds = $creds | Where-Object { $Name -contains $_.name }
    $missing = $Name | Where-Object { $creds.name -notcontains $_ }
    if ($missing) { Write-Warning "Not found: $($missing -join ', ')" }
}
if (-not $creds) { Write-Warning 'No credentials to reveal.'; return }

# --- Reveal ---
$lines = @("# Generated by tools/creds/pull-creds.ps1 on $(Get-Date -Format s). DO NOT COMMIT.")
foreach ($c in $creds) {
    $r = Invoke-RestMethod -Method Post -Uri "$Base/$($c.uuid)/reveal/" -Headers $Headers
    if ($r.credential_key -notmatch '^[A-Za-z_][A-Za-z0-9_]*$') {
        Write-Warning "Skipping '$($c.name)': key '$($r.credential_key)' is not a valid env var name."
        continue
    }
    $value = [string]$r.value -replace '\\', '\\' -replace '"', '\"' -replace "`r?`n", '\n'
    $lines += "# $($c.name)$(if ($r.expires_at) { " (expires $($r.expires_at))" })"
    $lines += "$($r.credential_key)=`"$value`""
    Write-Host "  + $($r.credential_key)  ($($c.name))"
}

Set-Content -Path $OutFile -Value $lines -Encoding utf8
Write-Host "Wrote $($creds.Count) credential(s) to $OutFile"
